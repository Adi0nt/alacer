/**
 * Scripted, repeatable client benchmark.
 *
 * <p>Enabled with {@code -Dalacer.benchmark=true}. The runner loads a fresh copy of a world with
 * a fixed seed, puts the player in spectator mode with time and weather frozen, optionally
 * places a grid of motionless mobs and chests, then drives the camera along fixed,
 * wall-clock-timed paths while the profiler captures every frame:
 *
 * <ul>
 * <li>{@code static}: camera held still at ground level (steady-state rendering cost).</li>
 * <li>{@code pan}: camera rotating in place (visibility and culling work every frame).</li>
 * <li>{@code fly}: camera moving at 20 blocks/s (chunk loading, building and uploading).</li>
 * </ul>
 *
 * <p>The base world {@code alacer-benchmark} is generated by the first run (discard that run's
 * results) and never modified afterwards: every later run copies it to
 * {@code alacer-benchmark-run} and plays the copy, so entities spawned by one run cannot leak
 * into the next. Results are written to {@code <gameDir>/alacer/benchmarks/<timestamp>-<label>/}
 * and the game exits when done (unless {@code -Dalacer.benchmark.exit=false}).
 *
 * <p>With {@code -Dalacer.benchmark.toggle=<runtime-toggleable option>}, the static and pan
 * phases instead run as four segments each (A, B, B, A) with the option off for A and on for
 * B, so both variants are measured in the same process. Separate launches can land in
 * different graphics-driver threading modes, which changes the cost of GL calls far more than
 * small optimizations do.
 *
 * <p>{@code benchmark.disableEntityShadows} is a benchmark-only toggle for attribution: B turns
 * the game's own Entity Shadows video option off. It changes the drawn image and is never a
 * config option. For it, {@code render.defaults} and {@code render.fastEntityShadows}, both
 * paths are warmed up before the scored segments, and detail profiling and verification must be off.
 *
 * <p>{@code -Dalacer.benchmark.shadowDiagnostic=true} is for {@code render.fastEntityShadows.verify}
 * only: the mobs keep their AI (they walk, so shadows cross block and chunk borders, and sheep eat
 * grass), and every 30 frames the cells diagonally between nearby mobs, inside their shadows,
 * cycle through glowstone (block light), stone slab (neighbor light) and air, so block states and
 * light data under the shadows change during the run. Not a performance scenario.
 *
 * <p>{@code -Dalacer.benchmark.particles=true} is the dedicated particle scenario: no mobs or
 * chests, and from the first settle on, every client tick (before the world and particle
 * manager tick) emits a fixed schedule from 16 stationary emitters 4-11.5 blocks around the
 * camera: one 64-particle stone block break, 48 smoke, 32 flame, 48 redstone dust, 16 small and
 * 2 large explosion particles, times {@code alacer.benchmark.particleScale} (1-8, default 1).
 * Emitter heights come from the copied world's terrain; positions, jitter and explosion sizes
 * come from a seeded generator, so every launch emits the same schedule. Each particle's own
 * lifetime and motion still use vanilla's unseeded randomness; the per-frame particle counters
 * show the resulting load. The game's Particles option is set to All. Phases are
 * {@code static} and {@code pan} (no flight, which would leave the emitters behind), or the
 * usual A/B/B/A segments; {@code benchmark.disableParticles} as the toggle stops the emission
 * and clears the particles in B, to attribute what they cost.
 *
 * <p>{@code -Dalacer.benchmark.particleDiagnostic=true} is for {@code render.fastParticleLight.verify}
 * only: it adds smoke above the build limit and flames below y = 0, and every 30 frames the block
 * under each emitter cycles through glowstone (block light), stone slab (neighbor light) and air,
 * so light and block states around the particles change during the run. Not a performance scenario.
 *
 * <p>{@code -Dalacer.benchmark.particleRemovalDiagnostic=true} is for
 * {@code render.fastParticleRemoval.verify} only: every tick it also adds {@link ParticleProbes}
 * that change layers while ticking, add particles to their own list while it ticks (evicting at
 * the 4,000 cap at scale 2), share a network id with a live particle, appear twice in one list,
 * or override {@code equals}. Not a performance scenario.
 *
 * <p>{@link StabilityOptions} (all opt-in, absent by default) add identical reference phases before and
 * after the scored phases, override recorded phase lengths, add repeated in-process segments or short
 * toggle blocks, and record the client thread's logical processor and the mobs' movement per phase.
 *
 * <p>Spectator mode is used so the camera can pass through terrain without the server
 * correcting its position; it also disables hand and block-outline rendering, which is a
 * small, constant difference from survival play.
 */
