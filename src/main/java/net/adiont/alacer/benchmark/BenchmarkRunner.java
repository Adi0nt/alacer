	/** stop() only clears the run-loop flag: one unrecorded frame can still render afterwards. */
	private void stopClient() {
		if (this.originalVbo != null && this.minecraft.options.useVbo != this.originalVbo) {
			this.minecraft.options.useVbo = this.originalVbo;
			// Use vanilla's lifecycle for backend/storage/sky consistency even in that final frame.
			this.minecraft.worldRenderer.reload();
		}
		this.minecraft.stop();
	}

	private static void summarize(JsonWriter json, Phase phase, ProfileReport report) {
		SeriesStats frame = report.stats(FrameProfiler.COL_FRAME);
		SeriesStats alloc = report.stats(FrameProfiler.COL_ALLOC_BYTES);
		SeriesStats pending = report.stats(FrameProfiler.COL_PENDING_CHUNKS);
		json.beginObject(phase.name);
		json.fields("config", phase.config);
		json.field("frames", frame.count);
		json.field("discarded_setup_frames", phase.discardedSetupFrames);
		json.field("target_seconds", phase.seconds);
		json.field("recorded_wall_seconds", phase.wallNanos / NANOS);
		json.field("dropped_frames", phase.dropped);
		json.field("settle_s", phase.settleSeconds);
		json.field("entities", phase.entitiesAtStart);
		json.field("avg_fps", frame.averageFps());
		json.field("one_percent_low_fps", frame.fpsAt(frame.worst1PercentMean));
		json.field("frame_p50_ms", frame.p50 / 1.0e6);
		json.field("frame_p99_ms", frame.p99 / 1.0e6);
		json.field("frame_p99_9_ms", frame.p999 / 1.0e6);
		json.field("frame_max_ms", frame.max / 1.0e6);
		// CPU time is sampled at phase boundaries only (thread CPU clocks are coarse on Windows).
		json.field("client_thread_cpu_ms_per_frame", frame.count == 0 ? 0.0 : phase.threadCpuNanos / 1.0e6 / frame.count);
		json.field("client_thread_cpu_utilization", phase.wallNanos == 0 ? 0.0 : (double) phase.threadCpuNanos / phase.wallNanos);
		json.field("process_cpu_cores", phase.processCpuNanos < 0 || phase.wallNanos == 0 ? -1.0 : (double) phase.processCpuNanos / phase.wallNanos);
		for (FrameProfiler.Section section : FrameProfiler.Section.values()) {
			json.field(section.name().toLowerCase(Locale.ROOT) + "_mean_ms", report.stats(FrameProfiler.column(section)).mean / 1.0e6);
		}
		for (FrameProfiler.Counter counter : FrameProfiler.Counter.values()) {
			json.field(counter.name().toLowerCase(Locale.ROOT) + "_mean", report.stats(FrameProfiler.column(counter)).mean);
		}
		json.field("alloc_mean_bytes", alloc.mean);
		json.field("pending_chunks_mean", pending.mean);
		if (phase.processors != null) {
			json.beginObject("client_processor_frames");
			for (int i = 0; i < phase.processors.length; i++) {
				if (phase.processors[i] > 0) {
					json.field(String.valueOf(i), phase.processors[i]);
				}
			}
			json.endObject();
			json.field("client_processor_unknown_frames", phase.unknownProcessorFrames);
		}
		if (phase.mobPoseResult != null) {
			json.beginObject("mob_pose");
			json.field("mobs_start", (long) phase.mobPoseResult[0]);
			json.field("mobs_end", (long) phase.mobPoseResult[1]);
			json.field("mobs_both", (long) phase.mobPoseResult[2]);
			json.field("max_move_blocks", phase.mobPoseResult[3]);
			json.field("max_turn_degrees", phase.mobPoseResult[4]);
			json.endObject();
		}
		if (phase.updateLatencies != null) {
			long[] values = phase.updateLatencies;
			SeriesStats latency = SeriesStats.compute(values, values.length, new long[values.length]);
			json.field("update_latency_count", latency.count);
			json.field("update_latency_overflow", phase.updateLatencyOverflow);
			json.field("update_latency_mean_ms", latency.mean / 1.0e6);
			json.field("update_latency_p50_ms", latency.p50 / 1.0e6);
			json.field("update_latency_p90_ms", latency.p90 / 1.0e6);
			json.field("update_latency_p99_ms", latency.p99 / 1.0e6);
			json.field("update_latency_max_ms", latency.max / 1.0e6);
		}
		json.endObject();
	}

	private void fail(String reason) {
		if (this.failed) {
			return;
		}
		this.failed = true;
		this.stage = Stage.DONE;
		Alacer.LOGGER.error("Benchmark aborted: {}", reason);
		if (this.exitWhenDone && this.minecraft != null) {
			stopClient();
		}
	}

	/**
	 * Ends the process if the benchmark has not finished within {@code seconds} of startup
	 * (0 disables). The in-game stage timeouts only work while frames are still running; this
	 * also covers a hung client thread, so a scripted series of launches cannot wait forever.
	 * A normal run takes about two minutes; generating the base world takes longer.
	 */
	private void startWatchdog(long seconds) {
		if (seconds <= 0) {
			return;
		}
		long deadline = System.nanoTime() + seconds * 1_000_000_000L;
		Thread watchdog = new Thread(() -> {
			while (this.stage != Stage.DONE) {
				if (System.nanoTime() - deadline > 0) {
					Alacer.LOGGER.error("Benchmark timed out after {} s in stage {} (phase {} of {}); set alacer.benchmark.timeout to change the limit",
						seconds, this.stage, this.phaseIndex, this.phases.size());
					if (this.exitWhenDone) {
						// The client thread may be hung, so a normal shutdown cannot be relied on.
						Runtime.getRuntime().halt(3);
					}
					return;
				}
				try {
					Thread.sleep(1000);
				} catch (InterruptedException e) {
					return;
				}
			}
		}, "Alacer benchmark watchdog");
		watchdog.setDaemon(true);
		watchdog.start();
	}

	/** Label describing the run, used in the output directory name. */
	public static String defaultLabel(Map<String, String> config) {
		StringBuilder label = new StringBuilder(System.getProperty("alacer.benchmark.label", "run"));
		label.append("-vis_").append("true".equals(config.get("render.fastChunkVisibility")) ? "on" : "off");
		label.append("-ecl_").append("true".equals(config.get("render.fastEntityChunkLookup")) ? "on" : "off");
		label.append("-ent").append(longProperty("alacer.benchmark.entities", 0));
		String toggle = System.getProperty("alacer.benchmark.toggle");
		if (toggle != null && !toggle.trim().isEmpty()) {
			label.append("-ab");
		}
		return label.toString();
	}

	/**
	 * Reads a numeric system property, tolerating surrounding whitespace. Unlike
	 * {@link Long#getLong}, an unparsable value is an error rather than a silent default, so a
	 * mistyped benchmark option cannot quietly produce a different scenario.
	 */
	private static long longProperty(String name, long def) {
		String value = System.getProperty(name);
		if (value == null) {
			return def;
		}
		try {
			return Long.parseLong(value.trim());
		} catch (NumberFormatException e) {
			throw new IllegalArgumentException("Invalid value for " + name + ": '" + value + "'", e);
		}
	}
