	/** The scenario's own phases, exactly as without {@link StabilityOptions}. */
	private void addScenarioPhases(double scale) {
		if (this.chunkEdit) {
			if (!this.chunkFlight.isEmpty() || this.backendScenario || this.particleScenario || this.toggleKey != null || this.shadowDiagnostic
				|| Boolean.getBoolean("alacer.benchmark.cloudSweep") || this.entityCount != 0 || this.chestCount != 0
				|| this.requestedVbo == null || !Double.isFinite(scale) || scale <= 0) {
				throw new IllegalArgumentException("chunkEdit requires explicit backend, positive scale and no other scenario/toggle/population");
			}
			for (int i = 0; i < ChunkEditScenario.NAMES.length; i++) {
				final int phase = i;
				this.phases.add(new Phase(ChunkEditScenario.NAMES[i], ChunkEditScenario.SECONDS[i] * scale,
					(t, out) -> ChunkEditScenario.pose(phase, t, this.anchorX, this.groundY, this.anchorZ, out)));
			}
			return;
		}
		if (!this.chunkFlight.isEmpty()) {
			double height = ChunkFlightScenario.height(this.chunkFlight);
			if (this.backendScenario || this.particleScenario || this.toggleKey != null || this.shadowDiagnostic
				|| Boolean.getBoolean("alacer.benchmark.cloudSweep") || this.entityCount != 0 || this.chestCount != 0
				|| this.requestedVbo == null || !Double.isFinite(scale) || scale <= 0) {
				throw new IllegalArgumentException("chunkFlight requires explicit backend, positive scale and no other scenario/toggle/population");
			}
			for (int i = 0; i < ChunkFlightScenario.NAMES.length; i++) {
				final int phase = i;
				this.phases.add(new Phase(ChunkFlightScenario.NAMES[i], ChunkFlightScenario.SECONDS[i] * scale,
					(t, out) -> ChunkFlightScenario.pose(phase, t, this.anchorX, this.groundY, this.anchorZ, height, out)));
			}
			return;
		}
		if (this.backendScenario) {
			if (this.toggleKey != null || this.shadowDiagnostic || Boolean.getBoolean("alacer.benchmark.cloudSweep")
				|| this.entityCount != 0 || this.chestCount != 0) {
				throw new IllegalArgumentException("backendScenario requires no toggles, cloud/shadow sweep or added entities/chests");
			}
			for (int i = 0; i < BackendScenario.NAMES.length; i++) {
				BackendScenario.View view = BackendScenario.VIEWS[i];
				this.phases.add(new Phase(BackendScenario.NAMES[i], BackendScenario.SECONDS[i] * scale,
					(t, out) -> BackendScenario.pose(view, t, this.anchorX, this.groundY, this.anchorZ, out)));
			}
			return;
		}
		if (this.particleScenario) {
			if (this.backendScenario || this.shadowDiagnostic || Boolean.getBoolean("alacer.benchmark.cloudSweep")
				|| this.entityCount != 0 || this.chestCount != 0) {
				throw new IllegalArgumentException("particles requires no backend scenario, cloud/shadow sweep or added entities/chests");
			}
			if (this.particleScale < 1 || this.particleScale > 8) {
				throw new IllegalArgumentException("particleScale must be 1 to 8");
			}
		} else if (DISABLE_PARTICLES.equals(this.toggleKey) || this.particleDiagnostic || this.particleRemovalDiagnostic) {
			throw new IllegalArgumentException("disableParticles and the particle diagnostics require alacer.benchmark.particles=true");
		}
		if (warmsBothPaths(this.toggleKey)) {
			Map<String, String> options = Alacer.get().config().describe();
			if (Alacer.get().config().profilerChunkDetail) {
				throw new IllegalArgumentException(this.toggleKey + " comparison requires profiler.chunkDetail=false");
			}
			if (Alacer.get().config().profilerFrustumTiming) {
				throw new IllegalArgumentException(this.toggleKey + " comparison requires profiler.frustumTiming=false");
			}
			if (Alacer.get().config().profilerEntityDetail) {
				throw new IllegalArgumentException(this.toggleKey + " comparison requires profiler.entityDetail=false");
			}
			if (Alacer.get().config().profilerParticleDetail) {
				throw new IllegalArgumentException(this.toggleKey + " comparison requires profiler.particleDetail=false");
			}
			if (Alacer.get().config().profilerParticleLightRepeats) {
				throw new IllegalArgumentException(this.toggleKey + " comparison requires profiler.particleLightRepeats=false");
			}
			for (Map.Entry<String, String> option : options.entrySet()) {
				if (option.getKey().endsWith(".verify") && "true".equals(option.getValue())) {
					throw new IllegalArgumentException(this.toggleKey + " comparison requires verification off: " + option.getKey());
				}
			}
		}
		if (Boolean.getBoolean("alacer.benchmark.cloudSweep")) {
			addCloudSweep(scale);
			return;
		}
		if (this.toggleKey != null) {
			addToggleSegments(scale);
			return;
		}

		this.phases.add(new Phase("static", 10 * scale, (t, out) -> {
			out[0] = this.anchorX;
			out[1] = this.groundY + 1.0;
			out[2] = this.anchorZ;
			out[3] = 45.0;
			out[4] = 5.0;
		}));
		this.phases.add(new Phase("pan", 15 * scale, (t, out) -> {
			out[0] = this.anchorX;
			out[1] = this.groundY + 1.0;
			out[2] = this.anchorZ;
			out[3] = 45.0 + 360.0 * t / 7.5;
			out[4] = 5.0;
		}));
		if (this.particleScenario) {
			return;
		}
		this.phases.add(new Phase("fly", 20 * scale, (t, out) -> {
			out[0] = this.anchorX + 20.0 * t;
			out[1] = this.groundY + 24.0;
			out[2] = this.anchorZ;
			out[3] = -90.0;
			out[4] = 20.0;
		}));
	}

	/**
	 * In-process A/B: both variants run in the same JVM, with the same JIT state and graphics
	 * driver mode. Segments run A, B, B, A so warm-up and drift affect both equally; each pan
	 * segment is exactly one turn. The fly path is not repeated, because a second pass would find
	 * its chunks already loaded and would not be comparable.
	 */
	private void addToggleSegments(double scale) {
		CameraPath still = (t, out) -> {
			out[0] = this.anchorX;
			out[1] = this.groundY + 1.0;
			out[2] = this.anchorZ;
			out[3] = 45.0;
			out[4] = 5.0;
		};
		CameraPath turn = (t, out) -> {
			out[0] = this.anchorX;
			out[1] = this.groundY + 1.0;
			out[2] = this.anchorZ;
			out[3] = 45.0 + 360.0 * t / 7.5;
			out[4] = 5.0;
		};
		boolean warmBoth = warmsBothPaths(this.toggleKey);
		if (warmBoth) {
			addWarmup("warmup-static-a", 5 * scale, still, false);
			addWarmup("warmup-static-b", 5 * scale, still, true);
		}
		if (this.stability.toggleBlocks > 0) {
			// Opt-in short blocks in the stationary view only; pan segments are not repeated.
			for (String name : this.stability.toggleBlockNames()) {
				Phase phase = new Phase(name, this.stability.toggleSegmentSeconds, still);
				phase.toggle = StabilityOptions.isVariant(name);
				this.phases.add(phase);
			}
			return;
		}
		String[] order = Boolean.getBoolean("alacer.benchmark.toggleReverse")
			? new String[] {"b1", "a1", "a2", "b2"} : new String[] {"a1", "b1", "b2", "a2"};
		for (String segment : order) {
			Phase phase = new Phase("static-" + segment, 5 * scale, still);
			phase.toggle = segment.charAt(0) == 'b';
			this.phases.add(phase);
		}
		// The first turn reveals chunks the static view never compiled, so it is not steady state
		// and would penalize whichever variant ran first. It is recorded under a name the
		// comparison tool ignores.
		if (warmBoth) {
			addWarmup("warmup-pan-a", 7.5 * scale, turn, false);
			addWarmup("warmup-pan-b", 7.5 * scale, turn, true);
		} else {
			this.phases.add(new Phase("pan-warmup", 7.5 * scale, turn));
		}
		for (String segment : order) {
			Phase phase = new Phase("pan-" + segment, 7.5 * scale, turn);
			phase.toggle = segment.charAt(0) == 'b';
			this.phases.add(phase);
		}
	}

	/**
	 * Applies {@link StabilityOptions}: phase-length overrides, then the reference phases and repeat segments,
	 * all at the default static view. With a toggle they run with the option off (A).
	 */
	private void applyStability() {
		if (!this.stability.changesPhases()) {
			return;
		}
		if (Boolean.getBoolean("alacer.benchmark.cloudSweep")) {
			throw new IllegalArgumentException("stability phases are not supported with cloudSweep");
		}
		List<String> names = new ArrayList<>();
		for (Phase phase : this.phases) {
			names.add(phase.name);
		}
		this.stability.checkPhaseNames(names);
		for (int i = 0; i < this.phases.size(); i++) {
			Phase phase = this.phases.get(i);
			double seconds = this.stability.secondsFor(phase.name, phase.seconds);
			if (seconds != phase.seconds) {
				Phase longer = new Phase(phase.name, seconds, phase.path);
				longer.toggle = phase.toggle;
				longer.setup = phase.setup;
				this.phases.set(i, longer);
			}
		}
		CameraPath reference = (t, out) -> {
			out[0] = this.anchorX;
			out[1] = this.groundY + 1.0;
			out[2] = this.anchorZ;
			out[3] = 45.0;
			out[4] = 5.0;
		};
		Boolean off = this.toggleKey == null ? null : Boolean.FALSE;
		if (this.stability.referenceSeconds > 0) {
			Phase pre = new Phase(StabilityOptions.REFERENCE_PRE, this.stability.referenceSeconds, reference);
			pre.toggle = off;
			this.phases.add(0, pre);
		}
		for (String name : this.stability.repeatNames()) {
			Phase segment = new Phase(name, this.stability.repeatSegmentSeconds, reference);
			segment.toggle = off;
			this.phases.add(segment);
		}
		if (this.stability.referencePost) {
			Phase post = new Phase(StabilityOptions.REFERENCE_POST, this.stability.referenceSeconds, reference);
			post.toggle = off;
			this.phases.add(post);
		}
	}

	/** Toggles measured with the Phase 10 protocol: both paths warmed, detail and verification off. */
	private static boolean warmsBothPaths(String key) {
		return "render.modernPipeline".equals(key) || "render.fastChunkNeighbours".equals(key) || "render.terrainShader".equals(key) || "render.terrainVaos".equals(key) || "render.directBufferUploads".equals(key)
			|| "render.defaults".equals(key) || "render.fastEntityShadows".equals(key)
			|| "render.fastChunkFrustum".equals(key) || "render.fastParticleLight".equals(key)
			|| "render.fastCameraSectionFaces".equals(key)
			|| "render.fastEntityLighting".equals(key) || "render.fastEntityRendererLookup".equals(key)
			|| "render.fastEntityCulling".equals(key) || "render.fastRayTrace".equals(key)
			|| "render.fastRandomDisplayTicks".equals(key) || "render.fastSoundThread".equals(key)
			|| "render.cameraHysteresis".equals(key) || "render.flatOcclusion".equals(key)
			|| "render.vectorFrustum".equals(key) || "render.fastWorkerAo".equals(key)
			|| "render.fastModelTransforms".equals(key)
			|| "render.fastParticleRemoval".equals(key)
			|| "render.fastParticleVertices".equals(key)
			|| "render.fastParticleLightEntry".equals(key)
			|| "render.reuseParticleLight".equals(key)
			|| "render.fastParticleMovement".equals(key)
			|| "render.reuseParticleBoxes".equals(key)
			|| "render.scalarParticleEntityQuery".equals(key)
			|| "render.reuseShadowPositions".equals(key)
			|| DISABLE_SHADOWS.equals(key) || DISABLE_PARTICLES.equals(key);
	}

	private void addWarmup(String name, double seconds, CameraPath path, boolean toggle) {
		Phase phase = new Phase(name, seconds, path);
		phase.toggle = toggle;
		this.phases.add(phase);
	}

	/** Diagnostic only: exercise cloud face bands, wrapping, color transitions and stereo passes. */
	private void addCloudSweep(double scale) {
		String[] scenes = {"below", "bands", "above", "wrap-negative", "wrap-positive", "rain", "anaglyph", "flat", "disabled", "fancy"};
		for (int index = 0; index < scenes.length; index++) {
			final int scene = index;
			Phase phase = new Phase("cloud-" + scenes[index], 5 * scale, (t, out) -> {
				out[0] = this.anchorX + 8 * t;
				out[1] = scene == 1 ? 118 + 5 * t / scale : scene == 2 ? 144 : 100;
				out[2] = this.anchorZ - 8 * t;
				if (scene == 3 || scene == 4) {
					out[0] = (scene == 3 ? -24588 : 24564) + 8 * t;
					out[2] = (scene == 3 ? -24588 : 24564) + 8 * t;
				}
				out[3] = 45;
				out[4] = scene == 2 ? 15 : -20;
			});
			phase.setup = () -> {
				this.minecraft.options.anaglyph = scene == 6;
				this.minecraft.options.cloudRenderMode = scene == 7 ? 1 : scene == 8 ? 0 : 2;
				if (scene == 5) {
					this.minecraft.player.sendChat("/time set 13000");
					this.minecraft.player.sendChat("/weather rain 1000000");
				}
			};
			this.phases.add(phase);
		}
	}

	/** Called once per frame on the client thread, before the frame's ticks and rendering. */
	public void onFrameStart() {
		if (this.stage == Stage.DONE) {
			return;
		}
		// Resolved lazily: the client entrypoint runs before the Minecraft instance exists.
		this.minecraft = Minecraft.getInstance();
		long now = System.nanoTime();
		this.stageFrames++;
		try {
			switch (this.stage) {
				case WAIT_FOR_MENU:
					if (this.minecraft.screen instanceof TitleScreen && this.stageFrames > 20) {
						loadWorld();
						enter(Stage.WAIT_FOR_WORLD, now);
					}
					break;
				case WAIT_FOR_WORLD:
					if (this.minecraft.world != null && this.minecraft.player != null && this.minecraft.screen == null) {
						configureWorld();
						enter(Stage.CONFIGURE, now);
					} else if (now - this.stageStart > 180 * 1_000_000_000L) {
						fail("world did not load within 180 s");
					}
					break;
				case CONFIGURE:
					// Give the server time to apply the commands and send the spawn chunks.
					if (now - this.stageStart > 3 * 1_000_000_000L && resolveAnchor()) {
						populate();
						enter(Stage.POPULATE, now);
					}
					break;
				case POPULATE:
					hold(this.phases.get(0), 0.0);
					if (this.spawnedEntities >= 0 && now - this.stageStart > 2 * 1_000_000_000L) {
						Alacer.LOGGER.info("Benchmark: placed {} mobs and {} chests; client sees {} entities",
							this.spawnedEntities, this.chestCount, this.minecraft.world.getEntities().size());
						beginSettle(this.phases.get(0), now);
					} else if (now - this.stageStart > 30 * 1_000_000_000L) {
						fail("population did not finish within 30 s");
					}
					break;
				case SETTLE:
					Phase next = this.phases.get(this.phaseIndex);
					hold(next, 0.0);
					// Between toggle segments the scene is already settled; a short pause suffices. Particles
					// live up to about 3 s (100 ticks for the longest smoke), so their scenario waits longer
					// for the population to return to steady state after a switch.
					double minimum = next == this.phases.get(0) ? 10.0 : this.particleScenario ? 5.0 : this.toggleKey != null ? 1.0 : 3.0;
					if (settled(now, minimum)) {
						next.settleSeconds = (now - this.stageStart) / NANOS;
						if (this.joinSettleSeconds < 0) {
							this.joinSettleSeconds = next.settleSeconds;
						}
						startRecording(next, now);
					}
					break;
				case PHASE:
					double t = (now - this.stageStart) / NANOS;
					if (t >= this.recording.seconds) {
						stopRecording(this.recording, now);
						if (this.screenshotAtEndPose) {
							// Render one unrecorded frame at the phase's exact end pose and capture it next frame,
							// so the camera angle does not depend on the frame rate.
							hold(this.recording, this.recording.seconds);
							enter(Stage.CAPTURE, now);
							break;
						}
						if (this.screenshots) {
							// The framebuffer still holds the previous frame at this point.
							takeScreenshot(this.recording);
						}
						endPhase(now);
					} else {
						hold(this.recording, t);
						if (this.shadowDiagnostic && this.stageFrames % 30 == 0) {
							toggleDiagnosticBlocks();
						}
						if (this.particleDiagnostic && this.stageFrames % 30 == 0) {
							toggleParticleCells();
						}
						if (this.chunkEdit && this.phaseIndex == ChunkEditScenario.EDIT_PHASE) {
							editDueBursts(t);
						}
					}
					break;
				case CAPTURE:
					// The framebuffer holds the frame rendered at the end pose.
					takeScreenshot(this.recording);
					endPhase(now);
					break;
				default:
					break;
			}
		} catch (RuntimeException | IOException e) {
			fail("unexpected error: " + e);
			Alacer.LOGGER.error("Benchmark failed", e);
		}
	}

	/**
	 * Called at the start of every client tick on the client thread, before the world and the
	 * particle manager tick, which is where vanilla's own particle sources emit.
	 */
	public void onTickStart() {
		if (!this.particleScenario || !this.particlesEnabled || this.minecraft == null || this.minecraft.world == null
			|| (this.stage != Stage.SETTLE && this.stage != Stage.PHASE)) {
			return;
		}
		FrameProfiler profiler = Alacer.get().profiler();
		profiler.begin(FrameProfiler.Section.PARTICLE_SPAWN);
		int spawned = emitParticles();
		profiler.end(FrameProfiler.Section.PARTICLE_SPAWN);
		profiler.count(FrameProfiler.Counter.PARTICLES_SPAWNED, spawned);
		this.particlesSpawned += spawned;
		this.particleTicks++;
	}

	/** Emitter points around the anchor, on the copied world's terrain; computed once. */
	private void placeParticleEmitters() {
		if (Boolean.getBoolean("alacer.benchmark.particleEntityQueryDiagnostic")) {
			if (!Alacer.get().config().scalarParticleEntityQuery || !Alacer.get().config().verifyScalarParticleEntityQuery) {
				throw new IllegalArgumentException("particleEntityQueryDiagnostic requires scalar query and verification");
			}
			ParticleEntityQueryChecks.run(this.minecraft.world, this.anchorX, this.groundY, this.anchorZ);
		}
		if (Boolean.getBoolean("alacer.benchmark.particleBoxDiagnostic")) {
			if (!Alacer.get().config().reuseParticleBoxes || !Alacer.get().config().verifyReuseParticleBoxes) {
				throw new IllegalArgumentException("particleBoxDiagnostic requires reuseParticleBoxes and its verification");
			}
			ParticleBoxChecks.run(this.minecraft.world, this.anchorX, this.groundY, this.anchorZ);
		}
		if (Boolean.getBoolean("alacer.benchmark.particleMovementDiagnostic")) {
			if (!Alacer.get().config().fastParticleMovement || !Alacer.get().config().verifyFastParticleMovement) {
				throw new IllegalArgumentException("particleMovementDiagnostic requires fastParticleMovement and its verification");
			}
			ParticleMovementChecks.run(this.minecraft.world, this.anchorX, this.groundY, this.anchorZ);
		}
		this.particleEmitters = new double[PARTICLE_EMITTERS * 3];
		this.particleTops = new int[PARTICLE_EMITTERS];
		for (int i = 0; i < PARTICLE_EMITTERS; i++) {
			double angle = 0.2 + i * (2.0 * Math.PI / PARTICLE_EMITTERS);
			double radius = 4.0 + 2.5 * (i % 4);
			double x = this.anchorX + radius * Math.cos(angle);
			double z = this.anchorZ + radius * Math.sin(angle);
			int top = this.minecraft.world.getHeight(new BlockPos(x, 0.0, z)).getY();
			this.particleTops[i] = top;
			this.particleEmitters[i * 3] = x;
			this.particleEmitters[i * 3 + 1] = top + 0.5 + 0.75 * (i % 3);
			this.particleEmitters[i * 3 + 2] = z;
		}
		Alacer.LOGGER.info("Benchmark: particle emitters {}", describeEmitters());
	}

	private String describeEmitters() {
		StringBuilder out = new StringBuilder();
		for (int i = 0; i < PARTICLE_EMITTERS; i++) {
			out.append(i == 0 ? "" : " ").append(String.format(Locale.ROOT, "%.2f,%.2f,%.2f",
				this.particleEmitters[i * 3], this.particleEmitters[i * 3 + 1], this.particleEmitters[i * 3 + 2]));
		}
		return out.toString();
	}

	/** One tick of the fixed particle schedule; returns the number of particles added. */
	private int emitParticles() {
		if (this.particleEmitters == null) {
			placeParticleEmitters();
		}
		net.minecraft.client.ParticleManager particles = this.minecraft.particleManager;
		Random random = this.particleRandom;
		BlockState stone = Blocks.STONE.defaultState();
		int added = 0;
		for (int round = 0; round < this.particleScale; round++) {
			int point = nextEmitter();
			particles.addBlockMiningParticles(new BlockPos(this.particleEmitters[point * 3],
				this.particleEmitters[point * 3 + 1], this.particleEmitters[point * 3 + 2]), stone);
			added += 64;
			added += emit(particles, ParticleType.SMOKE_NORMAL, 48, 0.0);
			added += emit(particles, ParticleType.FLAME, 32, 0.0);
			added += emit(particles, ParticleType.REDSTONE, 48, 0.0);
			added += emit(particles, ParticleType.EXPLOSION_NORMAL, 16, 0.05);
			for (int i = 0; i < 2; i++) {
				point = nextEmitter();
				// Large explosions read velocityX as their size: 1 - 0.5 * velocityX.
				if (particles.addParticle(ParticleType.EXPLOSION_LARGE.getId(), this.particleEmitters[point * 3] + jitter(random),
					this.particleEmitters[point * 3 + 1] + jitter(random), this.particleEmitters[point * 3 + 2] + jitter(random),
					random.nextDouble(), 0.0, 0.0) != null) {
					added++;
				}
			}
		}
		if (this.particleRemovalDiagnostic) {
			int point = nextEmitter();
			int probes = ParticleProbes.emit(particles, this.minecraft.world, random, this.particleEmitters[point * 3],
				this.particleEmitters[point * 3 + 1], this.particleEmitters[point * 3 + 2], this.particleTicks);
			this.particleProbes += probes;
			added += probes;
		}
		if (this.particleDiagnostic) {
			for (int i = 0; i < 16; i++) {
				if (particles.addParticle(ParticleType.SMOKE_NORMAL.getId(), this.anchorX + jitter(random) * 4, 255.2, this.anchorZ + jitter(random) * 4,
					0.0, 0.0, 0.0) != null) {
					added++;
				}
				if (particles.addParticle(ParticleType.FLAME.getId(), this.anchorX + 3 + jitter(random) * 4, -1.5, this.anchorZ + jitter(random) * 4,
					0.0, 0.0, 0.0) != null) {
					added++;
				}
			}
		}
		return added;
	}

	/** Particle diagnostic: cycles the block under each emitter (server thread). */
	private void toggleParticleCells() {
		if (this.particleTops == null) {
			return;
		}
		IntegratedServer server = this.minecraft.getServer();
		int step = this.particleToggles++;
		double[] emitters = this.particleEmitters;
		int[] tops = this.particleTops;
		server.executeTask(() -> {
			ServerWorld world = server.getWorld(0);
			for (int i = 0; i < PARTICLE_EMITTERS; i++) {
				BlockPos cell = new BlockPos(emitters[i * 3], tops[i], emitters[i * 3 + 2]);
				int state = (step + i) % 3;
				world.setBlockState(cell, state == 0 ? Blocks.GLOWSTONE.defaultState()
					: state == 1 ? Blocks.STONE_SLAB.defaultState() : Blocks.AIR.defaultState());
			}
		});
	}

	private int emit(net.minecraft.client.ParticleManager particles, ParticleType type, int count, double speed) {
		Random random = this.particleRandom;
		int added = 0;
		for (int i = 0; i < count; i++) {
			int point = nextEmitter();
			double vx = speed * random.nextGaussian();
			double vy = speed * random.nextGaussian();
			double vz = speed * random.nextGaussian();
			if (particles.addParticle(type.getId(), this.particleEmitters[point * 3] + jitter(random),
				this.particleEmitters[point * 3 + 1] + jitter(random), this.particleEmitters[point * 3 + 2] + jitter(random),
				vx, vy, vz) != null) {
				added++;
			}
		}
		return added;
	}

	private int nextEmitter() {
		int point = this.particleCursor;
		this.particleCursor = (point + 1) % PARTICLE_EMITTERS;
		return point;
	}

	private static double jitter(Random random) {
		return (random.nextDouble() - 0.5) * 0.6;
	}

	/** Chunk edit scenario: issues the bursts due by phase time {@code t} on the server thread, in order. */
	private void editDueBursts(double t) {
		int due = ChunkEditScenario.burstsDue(t);
		while (this.editBursts < due) {
			int burst = this.editBursts++;
			IntegratedServer server = this.minecraft.getServer();
			double ax = this.anchorX, az = this.anchorZ;
			server.executeTask(() -> {
				ServerWorld world = server.getWorld(0);
				if (this.editCells == null) {
					int[] cells = new int[ChunkEditScenario.CELLS * 3];
					for (int cell = 0; cell < ChunkEditScenario.CELLS; cell++) {
						int[] column = ChunkEditScenario.column(cell, ax, az);
						cells[cell * 3] = column[0];
						cells[cell * 3 + 1] = world.getHeight(new BlockPos(column[0], 0, column[1])).getY();
						cells[cell * 3 + 2] = column[1];
					}
					this.editCells = cells;
					StringBuilder where = new StringBuilder();
					for (int cell = 0; cell < ChunkEditScenario.CELLS; cell++) {
						where.append(cell == 0 ? "" : " ").append(cells[cell * 3]).append(',').append(cells[cell * 3 + 1]).append(',').append(cells[cell * 3 + 2]);
					}
					Alacer.LOGGER.info("Benchmark: chunk edit cells {}", where);
				}
				BlockState state = ChunkEditScenario.places(burst) ? Blocks.STONE.defaultState() : Blocks.AIR.defaultState();
				for (int cell = 0; cell < ChunkEditScenario.CELLS; cell++) {
					world.setBlockState(new BlockPos(this.editCells[cell * 3], this.editCells[cell * 3 + 1], this.editCells[cell * 3 + 2]), state);
				}
			});
		}
	}

	private void takeScreenshot(Phase phase) {
		Screenshot.take(this.minecraft.gameDir, "alacer-" + this.label + "-" + phase.name + ".png",
			this.minecraft.width, this.minecraft.height, this.minecraft.getRenderTarget());
	}

	private void endPhase(long now) throws IOException {
		this.recording = null;
		this.phaseIndex++;
		if (this.phaseIndex < this.phases.size()) {
			beginSettle(this.phases.get(this.phaseIndex), now);
		} else {
			finish();
		}
	}

	private void enter(Stage stage, long now) {
		this.stage = stage;
		this.stageStart = now;
		this.stageFrames = 0;
	}

	private static int benchmarkFpsLimit() {
		int max = (int) GameOptions.Option.FRAMERATE_LIMIT.getMax();
		int limit = Integer.getInteger("alacer.benchmark.fpsLimit", max);
		if (limit < 10 || limit > max) {
			throw new IllegalArgumentException("alacer.benchmark.fpsLimit must be 10-" + max + ", got " + limit);
		}
		return limit;
	}

	private void loadWorld() throws IOException {
		GameOptions options = this.minecraft.options;
		// Settings that would otherwise make results depend on window focus or display refresh rate.
		options.pauseOnUnfocus = false;
		// alacer.benchmark.fpsLimit (below the maximum) exercises the frame limiter; the default is unlimited.
		options.fpsLimit = benchmarkFpsLimit();
		options.vsync = false;
		GlErrorChecks.beforeDisplayChange();
		Display.setVSyncEnabled(false);
		options.viewDistance = this.viewDistance;
		if (this.particleScenario) {
			options.particles = 0;
		}
		if (this.requestedVbo != null) {
			this.originalVbo = options.useVbo;
			options.useVbo = this.requestedVbo;
		}

		Path saves = this.minecraft.gameDir.toPath().resolve("saves");
		Path base = saves.resolve(BASE_WORLD);
		String world;
		if (Files.isDirectory(base)) {
			Path copy = saves.resolve(RUN_WORLD);
			deleteRecursively(copy);
			copyRecursively(base, copy);
			if (!this.chunkFlight.isEmpty() || this.chunkEdit) {
				try (Stream<Path> paths = Files.walk(base)) {
					for (Path source : (Iterable<Path>) paths::iterator) {
						if (Files.isRegularFile(source) && !source.getFileName().toString().equals("session.lock")
							&& Files.mismatch(source, copy.resolve(base.relativize(source))) != -1) {
							throw new IOException("Fresh chunk-flight world copy differs: " + source);
						}
					}
				}
				Alacer.LOGGER.info("Benchmark: fresh chunk-flight world copy verified byte-identical (session.lock excluded)");
			}
			world = RUN_WORLD;
		} else {
			this.generationRun = true;
			world = BASE_WORLD;
			Alacer.LOGGER.warn("Benchmark: generating the base world; discard this run's results");
		}

		WorldSettings settings = new WorldSettings(SEED, WorldSettings.GameMode.SPECTATOR, true, false, WorldGeneratorType.DEFAULT).enableCommands();
		Alacer.LOGGER.info("Benchmark: loading world '{}' (seed {})", world, SEED);
		this.minecraft.startGame(world, BASE_WORLD, settings);
	}

	private static void copyRecursively(Path from, Path to) throws IOException {
		try (Stream<Path> paths = Files.walk(from)) {
			for (Path source : (Iterable<Path>) paths::iterator) {
				Path target = to.resolve(from.relativize(source).toString());
				if (Files.isDirectory(source)) {
					Files.createDirectories(target);
				} else if (!source.getFileName().toString().equals("session.lock")) {
					Files.copy(source, target, StandardCopyOption.REPLACE_EXISTING);
				}
			}
		}
	}

	/** Deletes the per-run world copy (only ever called on {@link #RUN_WORLD}). */
	private static void deleteRecursively(Path dir) throws IOException {
		if (!Files.exists(dir)) {
			return;
		}
		try (Stream<Path> paths = Files.walk(dir)) {
			List<Path> all = new ArrayList<>();
			paths.forEach(all::add);
			all.sort(Comparator.reverseOrder());
			for (Path p : all) {
				Files.delete(p);
			}
		}
	}

	private void configureWorld() {
		LocalClientPlayerEntity player = this.minecraft.player;
		player.sendChat("/gamemode 3");
		player.sendChat("/gamerule doDaylightCycle false");
		player.sendChat("/gamerule doMobSpawning false");
		player.sendChat("/time set 6000");
		player.sendChat("/weather clear 1000000");
	}

	private boolean resolveAnchor() {
		BlockPos spawn = this.minecraft.world.getSpawnPoint();
		// A reused world restores the player wherever the last run ended, possibly out of view
		// range of spawn, so move there first. The integrated server's owner may move freely.
		LocalClientPlayerEntity player = this.minecraft.player;
		player.setPositionAndAngles(spawn.getX() + 0.5, 150.0, spawn.getZ() + 0.5, 0.0F, 0.0F);
		player.velocityX = 0.0;
		player.velocityY = 0.0;
		player.velocityZ = 0.0;
		// An empty placeholder chunk also counts as "loaded"; wait for real terrain data.
		if (!this.minecraft.world.isChunkLoaded(spawn, false)) {
			return false;
		}
		int ground = this.minecraft.world.getHeight(spawn).getY();
		if (ground <= 0) {
			return false;
		}
		this.anchorX = spawn.getX() + 0.5;
		this.anchorZ = spawn.getZ() + 0.5;
		this.groundY = ground;
		Alacer.LOGGER.info("Benchmark: anchor at {}, {}, {}", this.anchorX, this.groundY, this.anchorZ);
		return true;
	}

	/**
	 * Places {@code alacer.benchmark.entities} motionless mobs (NoAI pigs, cows, sheep and wolves,
	 * cycled) on a 2-block grid centred on the anchor, and {@code alacer.benchmark.chests} chests on
	 * the cells between them. Runs on the integrated server thread.
	 */
	private void populate() {
		if (this.entityCount <= 0 && this.chestCount <= 0 && !this.backendScenario) {
			this.spawnedEntities = 0;
			return;
		}
		IntegratedServer server = this.minecraft.getServer();
		int ax = (int) Math.floor(this.anchorX);
		int az = (int) Math.floor(this.anchorZ);
		int mobs = this.entityCount;
		int chests = this.chestCount;
		server.executeTask(() -> {
			ServerWorld world = server.getWorld(0);
			if (this.backendScenario) {
				int ay = (int) this.groundY;
				for (int wall = 0; wall < 4; wall++) {
					for (int x = -6; x <= 6; x++) {
						for (int y = 1; y <= 7; y++) {
							BlockPos pos = new BlockPos(ax + x, ay + y, az + 10 + 4 * wall);
							world.setBlockState(pos, Blocks.STAINED_GLASS.defaultState());
							if (world.getBlockState(pos).getBlock() != Blocks.STAINED_GLASS) {
								throw new IllegalStateException("Backend glass scene placement failed at " + pos);
							}
							this.placedGlass++;
						}
					}
				}
				Alacer.LOGGER.info("Benchmark: backend scene placed {} stained-glass blocks in four overlapping walls (TRANSLUCENT)", this.placedGlass);
			}
			int placed = 0;
			int side = (int) Math.ceil(Math.sqrt(Math.max(mobs, chests) + 9));
			int half = side / 2;
			for (int i = 0; i < side * side && placed < mobs; i++) {
				int gx = i % side - half;
				int gz = i / side - half;
				if (Math.abs(gx) <= 1 && Math.abs(gz) <= 1) {
					continue; // keep the camera's own cell clear
				}
				BlockPos column = world.getHeight(new BlockPos(ax + gx * 2, 0, az + gz * 2));
				MobEntity mob;
				switch (placed % 4) {
					case 0:
						mob = new PigEntity(world);
						break;
					case 1:
						mob = new CowEntity(world);
						break;
					case 2:
						mob = new SheepEntity(world);
						break;
					default:
						mob = new WolfEntity(world);
						break;
				}
				mob.setNoAi(!this.shadowDiagnostic);
				mob.setPositionAndAngles(column.getX() + 0.5, column.getY(), column.getZ() + 0.5, (placed * 37) % 360, 0.0F);
				world.addEntity(mob);
				placed++;
			}
			int chestsPlaced = 0;
			for (int i = 0; i < side * side && chestsPlaced < chests; i++) {
				int gx = i % side - half;
				int gz = i / side - half;
				if (Math.abs(gx) <= 1 && Math.abs(gz) <= 1) {
					continue;
				}
				BlockPos column = world.getHeight(new BlockPos(ax + gx * 2 + 1, 0, az + gz * 2 + 1));
				world.setBlockState(column, Blocks.CHEST.defaultState());
				chestsPlaced++;
			}
			this.spawnedEntities = placed;
		});
	}

	/** Shadow diagnostic: cycles the cells between the 36 mobs nearest the anchor (server thread). */
	private void toggleDiagnosticBlocks() {
		IntegratedServer server = this.minecraft.getServer();
		int ax = (int) Math.floor(this.anchorX);
		int az = (int) Math.floor(this.anchorZ);
		int step = this.diagnosticToggles++;
		server.executeTask(() -> {
			ServerWorld world = server.getWorld(0);
			if (this.diagnosticHeights == null) {
				this.diagnosticHeights = new int[36];
				for (int i = 0; i < 36; i++) {
					this.diagnosticHeights[i] = world.getHeight(new BlockPos(ax + (i % 6 - 3) * 2 + 1, 0, az + (i / 6 - 3) * 2 + 1)).getY();
				}
			}
			for (int i = 0; i < 36; i++) {
				BlockPos cell = new BlockPos(ax + (i % 6 - 3) * 2 + 1, this.diagnosticHeights[i], az + (i / 6 - 3) * 2 + 1);
				int state = (step + i) % 3;
				world.setBlockState(cell, state == 0 ? Blocks.GLOWSTONE.defaultState()
					: state == 1 ? Blocks.STONE_SLAB.defaultState() : Blocks.AIR.defaultState());
			}
		});
	}

	private void beginSettle(Phase phase, long now) {
		enter(Stage.SETTLE, now);
		this.settledSince = 0L;
		if (phase.toggle != null) {
			if (DISABLE_SHADOWS.equals(this.toggleKey)) {
				if (this.originalEntityShadows == null) {
					this.originalEntityShadows = this.minecraft.options.entityShadows;
				}
				this.minecraft.options.entityShadows = !phase.toggle;
			} else if (DISABLE_PARTICLES.equals(this.toggleKey)) {
				this.particlesEnabled = !phase.toggle;
				if (!this.particlesEnabled) {
					// Vanilla's own clear (also used on world change): every particle list and emitter.
					this.minecraft.particleManager.setWorld(this.minecraft.world);
				}
			} else {
				Alacer.get().config().setToggle(this.toggleKey, phase.toggle);
			}
		}
		if (phase.setup != null) {
			phase.setup.run();
		}
		if (this.stability.freezeMobs) {
			freezeMobs(phase.name);
		}
		hold(phase, 0.0);
	}

	/** Opt-in: NoAI for every mob the server has loaded, so no mob walks or turns while a phase records. */
	private void freezeMobs(String phaseName) {
		IntegratedServer server = this.minecraft.getServer();
		server.executeTask(() -> {
			int frozen = 0;
			for (Entity entity : server.getWorld(0).getEntities()) {
				if (entity instanceof MobEntity mob && !mob.isNoAi()) {
					mob.setNoAi(true);
					frozen++;
				}
			}
			this.frozenMobs += frozen;
			if (frozen > 0) {
				Alacer.LOGGER.info("Benchmark: froze {} mobs before '{}'", frozen, phaseName);
			}
		});
	}

	/**
	 * The world counts as settled once no chunk builds have been pending for two seconds,
	 * after a minimum wait. Gives up after 90 seconds and records whatever state it reached.
	 */
	private boolean settled(long now, double minSeconds) {
		double elapsed = (now - this.stageStart) / NANOS;
		int pending = Alacer.get().pendingChunks();
		if (pending > 0) {
			this.settledSince = 0L;
		} else if (this.settledSince == 0L) {
			this.settledSince = now;
		}
		boolean quiet = this.settledSince != 0L && now - this.settledSince > 2 * 1_000_000_000L;
		return elapsed >= minSeconds && quiet || elapsed > 90.0;
	}

	private void startRecording(Phase phase, long now) {
		phase.config = configSnapshot();
		int capacity = (int) Math.min(Integer.MAX_VALUE / 2, (long) (phase.seconds * 4000) + 1000);
		phase.columns = new long[FrameProfiler.COLUMNS][capacity];
		phase.rows = 0;
		phase.entitiesAtStart = this.minecraft.world.getEntities().size();
		if (this.processorSampler != null) {
			phase.processors = new int[ProcessorSampler.MAX_PROCESSORS];
			phase.unknownProcessorFrames = 0;
		}
		// The following frame contains this setup's arrays/maps/logging. Arm capture at its
		// completed boundary instead of reporting it as a render frame or polluting the tails.
		phase.capturePending = true;
		this.recording = phase;
		GlCallStats.reset();
		EntityDrawDetails.reset();
		enter(Stage.PHASE, now);
		Alacer.LOGGER.info("Benchmark: recording '{}' for {} s (settled in {} s, {} entities)", phase.name, phase.seconds,
			String.format(Locale.ROOT, "%.1f", phase.settleSeconds), phase.entitiesAtStart);
	}

	private void stopRecording(Phase phase, long now) {
		if (ChunkUploadGpu.ENABLED) { ChunkUploadGpu.phase(null); }
		if (net.adiont.alacer.render.ParticleMovementCensus.ENABLED) {
			net.adiont.alacer.render.ParticleMovementCensus.phase(null);
		}
		if (net.adiont.alacer.render.ParticleDrawDiagnostics.ENABLED) {
			net.adiont.alacer.render.ParticleDrawDiagnostics.phase(null);
		}
		if (Alacer.get().config().profilerChunkLatency) {
			phase.updateLatencyOverflow = net.adiont.alacer.render.ChunkUpdateLatency.LOG.overflow();
			phase.updateLatencies = net.adiont.alacer.render.ChunkUpdateLatency.LOG.takeValues();
		}
		phase.wallNanos = now - phase.wallStart;
		phase.threadCpuNanos = this.threads.getCurrentThreadCpuTime() - phase.threadCpuStart;
		long process = processCpuTime();
		phase.processCpuNanos = process < 0 || phase.processCpuStart < 0 ? -1 : process - phase.processCpuStart;
		if (!phase.config.equals(configSnapshot())) {
			throw new IllegalStateException("Configuration changed while recording " + phase.name);
		}
		if (this.stability.mobPoseCheck && phase.mobPoses != null) {
			phase.mobPoseResult = StabilityOptions.compareMobPoses(phase.mobPoses, mobPoses());
		}
		GlCallStats.log(phase.name);
		EntityDrawDetails.log(phase.name);
	}

	/** Alacer's options plus the game's Entity Shadows option, which one toggle changes. */
